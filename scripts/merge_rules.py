"""Merge rule directories into one YAML file per language (demo image build step).

Opengrep spends several seconds collecting a directory of rule files on every run;
one merged file per language is faster, which matters for a live demo. Rules are
copied unchanged (MIT-licensed GitLab sast-rules plus this repo's own rules).

    python scripts/merge_rules.py <project root>
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

SOURCES = {
    "java": ["targets/sast-rules/java", "rules/java"],
    "javascript": ["targets/sast-rules/javascript"],
    "python": ["targets/sast-rules/python"],
}
HEADER = (
    "# Generated by scripts/merge_rules.py. Rules are unchanged copies from:\n"
    "#   GitLab sast-rules at the commit pinned in targets/commits.json (MIT)\n"
    "#   rules/ in this repository (MIT)\n"
)


def merge(root: Path, language: str) -> list[dict]:
    rules: list[dict] = []
    for rel in SOURCES[language]:
        for f in sorted((root / rel).rglob("*.yml")):
            doc = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
            rules += doc.get("rules", []) if isinstance(doc, dict) else []
    ids = [r["id"] for r in rules]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        raise SystemExit(f"duplicate rule ids in {language}: {sorted(dupes)[:5]}")
    return rules


def main(root: Path) -> None:
    out = root / "rules-merged"
    out.mkdir(exist_ok=True)
    for language in SOURCES:
        rules = merge(root, language)
        text = HEADER + yaml.safe_dump({"rules": rules}, sort_keys=False)
        (out / f"{language}.yml").write_text(text, encoding="utf-8")
        print(f"{language}: {len(rules)} rules")


if __name__ == "__main__":
    main(Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path.cwd())
